/**
 * Generates website/dashboard/lib/demo-catalog.generated.ts from the Go catalog source.
 * Run: node website/scripts/generate-demo-catalog.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../..');
const goPath = path.join(root, 'backend/internal/catalog/templates.go');
const outPath = path.join(root, 'website/dashboard/lib/demo-catalog.generated.ts');

const go = fs.readFileSync(goPath, 'utf8');

/** @param {string} block */
function parseEnvBlock(block) {
  const env = [];
  const envRe =
    /\{\s*Key:\s*"([^"]+)"(?:,\s*Value:\s*"([^"]*)")?(?:,\s*Description:\s*"([^"]*)")?(?:,\s*Required:\s*(true|false))?(?:,\s*Secret:\s*(true|false))?(?:,\s*Generate:\s*(true|false))?\s*\}/g;
  let m;
  while ((m = envRe.exec(block)) !== null) {
    env.push({
      key: m[1],
      value: m[2] ?? '',
      description: m[3] ?? '',
      required: m[4] === 'true',
      secret: m[5] === 'true',
      generate: m[6] === 'true',
    });
  }
  return env.length ? env : null;
}

/** @param {string} block */
function parseRequiredAddons(block) {
  const addons = [];
  const re = /\{Type:\s*"([^"]+)"\}/g;
  let m;
  while ((m = re.exec(block)) !== null) addons.push({ type: m[1] });
  return addons.length ? addons : undefined;
}

/** @param {string} block */
function parseVolumePaths(block) {
  const m = block.match(/VolumePaths:\s*\[]string\{([^}]+)\}/);
  if (!m) return undefined;
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

/** @param {string} block */
function parseTemplate(block) {
  const pick = (re) => {
    const m = block.match(re);
    return m ? m[1] : '';
  };
  const id = pick(/ID:\s*"([^"]+)"/);
  if (!id) return null;

  const port = Number(pick(/Port:\s*(\d+)/) || '0');
  const volumePaths = parseVolumePaths(block);
  const volumePath = pick(/VolumePath:\s*"([^"]*)"/);
  const env = parseEnvBlock(block);
  const requiredAddons = parseRequiredAddons(block);

  return {
    id,
    name: pick(/Name:\s*"([^"]+)"/),
    description: pick(/Description:\s*"([^"]+)"/),
    category: pick(/Category:\s*"([^"]+)"/),
    image: pick(/Image:\s*"([^"]+)"/),
    port,
    ...(volumePaths?.length ? { volumePaths } : volumePath ? { volumePath } : {}),
    ...(requiredAddons ? { requiredAddons } : {}),
    env,
    healthPath: pick(/HealthPath:\s*"([^"]*)"/) || '/',
    website: pick(/Website:\s*"([^"]+)"/),
    icon: pick(/Icon:\s*"([^"]+)"/),
    notes: pick(/Notes:\s*"([^"]*)"/),
  };
}

// Split on template object starts (heuristic: lines with ID: after an opening brace)
const templates = [];
const blocks = go.split(/\n\t\t\{/);
for (let i = 1; i < blocks.length; i++) {
  const block = '{' + blocks[i];
  const tpl = parseTemplate(block);
  if (tpl?.id) templates.push(tpl);
}

const header = `/* eslint-disable */
// AUTO-GENERATED by website/scripts/generate-demo-catalog.mjs — do not edit by hand.
import type { CatalogTemplate } from "./types";

export const DEMO_CATALOG: CatalogTemplate[] = `;

const body = JSON.stringify(templates, null, 2)
  .replace(/"([^"]+)":/g, '$1:')
  .replace(/"/g, '"')
  .replace(/: null/g, ': null')
  .replace(/env: \[\]/g, 'env: null');

// Fix JSON booleans and restore TypeScript null for empty env
let ts = templates
  .map((t) => {
    const lines = [`  {`];
    lines.push(`    id: ${JSON.stringify(t.id)},`);
    lines.push(`    name: ${JSON.stringify(t.name)},`);
    lines.push(`    description: ${JSON.stringify(t.description)},`);
    lines.push(`    category: ${JSON.stringify(t.category)},`);
    lines.push(`    image: ${JSON.stringify(t.image)},`);
    lines.push(`    port: ${t.port},`);
    if (t.volumePaths?.length) {
      lines.push(`    volumePaths: ${JSON.stringify(t.volumePaths)},`);
      lines.push(`    volumePath: "",`);
    } else {
      lines.push(`    volumePath: ${JSON.stringify(t.volumePath ?? '')},`);
    }
    if (t.requiredAddons?.length) {
      lines.push(`    requiredAddons: ${JSON.stringify(t.requiredAddons)},`);
    }
    if (t.env?.length) {
      lines.push(`    env: ${JSON.stringify(t.env)},`);
    } else {
      lines.push(`    env: null,`);
    }
    lines.push(`    healthPath: ${JSON.stringify(t.healthPath)},`);
    lines.push(`    website: ${JSON.stringify(t.website)},`);
    lines.push(`    icon: ${JSON.stringify(t.icon)},`);
    lines.push(`    notes: ${JSON.stringify(t.notes)},`);
    lines.push(`  },`);
    return lines.join('\n');
  })
  .join('\n');

const output = `${header}[\n${ts}\n];\n`;
fs.writeFileSync(outPath, output);
console.log(`Wrote ${templates.length} catalog templates to ${outPath}`);
